package codebase

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/system4us/graphAllTheThings/pkg/graph"
)

func TestSqlcSupportEndToEnd(t *testing.T) {
	dir := t.TempDir()

	files := map[string]string{
		"go.mod": "module example.com/shop\n\ngo 1.25\n",
		"sqlc.yaml": `version: "2"
sql:
  - engine: "postgresql"
    queries: "db/queries"
    schema: "db/schema"
    gen:
      go:
        package: "db"
        out: "internal/db"
`,
		"db/schema/001_init.sql": `
CREATE TABLE users (
	id BIGINT PRIMARY KEY,
	email TEXT NOT NULL
);

CREATE TABLE orders (
	id BIGINT PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id),
	total_cents INT NOT NULL
);
`,
		"db/queries/orders.sql": `
-- name: GetOrderWithUser :one
WITH recent AS (
	SELECT * FROM orders WHERE id = $1
)
SELECT recent.id, users.email
FROM recent
JOIN users ON users.id = recent.user_id;
`,
		"internal/db/models.go": `// Code generated by sqlc. DO NOT EDIT.
package db

type User struct {
	ID    int64
	Email string
}

type Order struct {
	ID         int64
	UserID     int64
	TotalCents int32
}
`,
		"internal/db/orders.sql.go": `// Code generated by sqlc. DO NOT EDIT.
// versions:
//   sqlc v1.27.0
// source: orders.sql

package db

import "context"

type Queries struct{}

func (q *Queries) GetOrderWithUser(ctx context.Context, id int64) (Order, error) {
	return Order{}, nil
}
`,
		"internal/api/handler.go": `package api

import (
	"net/http"
	"example.com/shop/internal/db"
)

type Server struct {
	q *db.Queries
}

func (s *Server) HandleGetOrder(w http.ResponseWriter, r *http.Request) {
	_, _ = s.q.GetOrderWithUser(r.Context(), 1)
}

func RegisterRoutes(mux *http.ServeMux, s *Server) {
	mux.HandleFunc("GET /orders/{id}", s.HandleGetOrder)
}
`,
	}

	for rel, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	g, err := New(dir).Extract(context.Background())
	if err != nil {
		t.Fatalf("Extract: %v", err)
	}

	hasEdge := func(fromSubstr, toSubstr, edgeType string) bool {
		for _, e := range g.Edges {
			if e.Type != edgeType {
				continue
			}
			fn, tn := g.Nodes[e.From], g.Nodes[e.To]
			fromMatch := fromSubstr == "" || containsSub(e.From, fromSubstr) || (fn != nil && containsSub(fn.Name, fromSubstr))
			toMatch := toSubstr == "" || containsSub(e.To, toSubstr) || (tn != nil && containsSub(tn.Name, toSubstr))
			if fromMatch && toMatch {
				return true
			}
		}
		return false
	}

	// 1. Models created from schema/*.sql
	if g.Nodes["model:users"] == nil || g.Nodes["model:orders"] == nil {
		t.Fatalf("expected model:users and model:orders from sqlc schema, got users=%v orders=%v",
			g.Nodes["model:users"] != nil, g.Nodes["model:orders"] != nil)
	}
	if !hasEdge("model:orders", "model:users", graph.EdgeReferences) {
		t.Errorf("expected REFERENCES edge model:orders -> model:users")
	}

	// 2. GENERATES edges
	if !hasEdge("db/queries/orders.sql", "internal/db/orders.sql.go", graph.EdgeGenerates) {
		t.Errorf("expected GENERATES edge db/queries/orders.sql -> internal/db/orders.sql.go")
	}
	if !hasEdge("db/schema/001_init.sql", "internal/db/models.go", graph.EdgeGenerates) {
		t.Errorf("expected GENERATES edge db/schema/001_init.sql -> internal/db/models.go")
	}

	// 3. Query function -> sql file (DEPENDS_ON) & -> models (USES_MODEL, ignoring CTE 'recent')
	if !hasEdge("GetOrderWithUser", "db/queries/orders.sql", graph.EdgeDependsOn) {
		t.Errorf("expected DEPENDS_ON edge GetOrderWithUser -> db/queries/orders.sql")
	}
	if !hasEdge("GetOrderWithUser", "model:orders", graph.EdgeUsesModel) {
		t.Errorf("expected USES_MODEL edge GetOrderWithUser -> model:orders")
	}
	if !hasEdge("GetOrderWithUser", "model:users", graph.EdgeUsesModel) {
		t.Errorf("expected USES_MODEL edge GetOrderWithUser -> model:users")
	}
	if g.Nodes["model:recent"] != nil {
		t.Errorf("CTE 'recent' should not be treated as a table model")
	}

	// 4. Route inherits USES_MODEL through handler -> GetOrderWithUser
	if !hasEdge("route:", "model:orders", graph.EdgeUsesModel) {
		t.Errorf("expected route -> model:orders USES_MODEL edge through sqlc query")
	}
	if !hasEdge("route:", "model:users", graph.EdgeUsesModel) {
		t.Errorf("expected route -> model:users USES_MODEL edge through sqlc query")
	}
}

func containsSub(s, sub string) bool {
	return len(sub) == 0 || (len(s) >= len(sub) && indexOf(s, sub) >= 0)
}

func indexOf(s, sub string) int {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}
	return -1
}
